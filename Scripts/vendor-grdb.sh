#!/bin/bash
# Re-creates Vendor/GRDB.swift from an upstream GRDB release.
#
# Why this exists: upstream GRDB only supports SQLCipher through Swift Package
# Manager if you fork it and edit Package.swift (see "GRDB+SQLCipher" comments
# in upstream's manifest). Instead of depending on a fork, the repository
# carries an unmodified copy of GRDB's sources plus the manifest written below,
# which applies exactly those documented edits.
#
# Usage: Scripts/vendor-grdb.sh [tag]      (default: the tag pinned below)
set -euo pipefail

TAG="${1:-v7.12.0}"
SQLCIPHER_VERSION="4.20.0"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/Vendor/GRDB.swift"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git clone --quiet --depth 1 --branch "$TAG" https://github.com/groue/GRDB.swift "$WORK/src"
COMMIT="$(git -C "$WORK/src" rev-parse HEAD)"

rm -rf "$DEST"
mkdir -p "$DEST/Sources"
cp -R "$WORK/src/GRDB" "$DEST/GRDB"
cp -R "$WORK/src/Sources/GRDBSQLCipher" "$DEST/Sources/GRDBSQLCipher"
cp "$WORK/src/LICENSE" "$DEST/LICENSE"
# Documentation is not needed to build.
rm -rf "$DEST/GRDB/Documentation.docc"

cat > "$DEST/Package.swift" <<MANIFEST
// swift-tools-version:6.1
// Vendored GRDB $TAG ($COMMIT), built against SQLCipher.
// Generated by Scripts/vendor-grdb.sh. Do not edit by hand.
//
// This is upstream's Package.swift with its documented "GRDB+SQLCipher" edits
// applied (system SQLite removed, SQLCipher added) and the test target dropped.

import PackageDescription

let swiftSettings: [SwiftSetting] = [
    .define("SQLITE_ENABLE_FTS5"),
    .define("SQLITE_ENABLE_SNAPSHOT"),
    .define("SQLITE_HAS_CODEC"),
    .define("SQLCipher"),
]
let cSettings: [CSetting] = [
    .define("SQLITE_HAS_CODEC"),
]

let package = Package(
    name: "GRDB",
    platforms: [
        .iOS(.v13),
        .macOS(.v10_15),
        .tvOS(.v13),
        .watchOS(.v7),
    ],
    products: [
        .library(name: "GRDB", targets: ["GRDB"]),
    ],
    dependencies: [
        .package(url: "https://github.com/sqlcipher/SQLCipher.swift.git", exact: "$SQLCIPHER_VERSION"),
    ],
    targets: [
        .target(
            name: "GRDBSQLCipher",
            dependencies: [.product(name: "SQLCipher", package: "SQLCipher.swift")]
        ),
        .target(
            name: "GRDB",
            dependencies: [
                .product(name: "SQLCipher", package: "SQLCipher.swift"),
                .target(name: "GRDBSQLCipher"),
            ],
            path: "GRDB",
            resources: [.copy("PrivacyInfo.xcprivacy")],
            cSettings: cSettings,
            swiftSettings: swiftSettings + [
                .enableUpcomingFeature("MemberImportVisibility"),
            ]),
    ],
    swiftLanguageModes: [.v6]
)
MANIFEST

cat > "$DEST/VENDORED.md" <<NOTE
# Vendored GRDB

- Upstream: https://github.com/groue/GRDB.swift
- Tag: $TAG
- Commit: $COMMIT
- SQLCipher: https://github.com/sqlcipher/SQLCipher.swift $SQLCIPHER_VERSION (official prebuilt xcframework, checksum-pinned by its manifest)

The \`GRDB/\` and \`Sources/GRDBSQLCipher/\` directories are byte-for-byte copies
of upstream at the commit above (minus \`Documentation.docc\`). Only
\`Package.swift\` differs: it is upstream's manifest with the "GRDB+SQLCipher"
edits its own comments describe. Regenerate with \`Scripts/vendor-grdb.sh\`.
NOTE

echo "Vendored GRDB $TAG ($COMMIT) into $DEST"
